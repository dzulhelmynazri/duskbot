  sky: { line: "#3f8fc9", fill: "#c4e9fb" },
  pink: { line: "#d0679a", fill: "#fbd3e4" },
  lilac: { line: "#8a6fd0", fill: "#e2d6fb" },
  lemon: { line: "#c9901a", fill: "#fbeeb0" },
  lime: { line: "#5f9e34", fill: "#d6f0bb" },
  peach: { line: "#b07a3f", fill: "#f8e2c2" },
